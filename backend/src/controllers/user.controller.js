import {
  getProfileService,
  updateProfileService,
  changePasswordService,
  updateProfileImageService,
  deleteAccountService,
  listUsersService,
  changeUserRoleService,
  getMeService
} from "../services/user.service.js";

export const getProfile = async (req, res) => {
  try {
    const userId = req.user.user_id;

    const profile = await getProfileService(userId);

    return res.status(200).json({
      success: true,
      message: "Profile fetched successfully",
      data: profile,
    });
  } catch (error) {
    return res.status(error.statusCode || 500).json({
      success: false,
      message: error.statusCode ? error.message : "Internal server error",
    });
  }
};

export const updateProfile = async (req, res) => {
  try {
    // Identity from the verified JWT only
    const userId = req.user.user_id;

    // Pick ONLY the allowed field; anything else in req.body is ignored
    const { username } = req.body;

    const profile = await updateProfileService(userId, { username });

    return res.status(200).json({
      success: true,
      message: "Profile updated successfully",
      data: profile,
    });
  } catch (error) {
    return res.status(error.statusCode || 500).json({
      success: false,
      message: error.statusCode ? error.message : "Internal server error",
    });
  }
};

export const changePassword = async (req, res) => {
  try {
    const userId = req.user.user_id;
    const { current_password, new_password } = req.body;

    await changePasswordService(userId, { current_password, new_password });

    return res.status(200).json({
      success: true,
      message: "Password changed successfully",
    });
  } catch (error) {
    return res.status(error.statusCode || 500).json({
      success: false,
      message: error.statusCode ? error.message : "Internal server error",
    });
  }
};

